VALID_LOCALES = ("ru", "uz-latn", "uz-cyr", "en")


def normalize_locale(raw: Optional[str]) -> str:
    value = (raw or "").strip().lower().replace("_", "-")
    aliases = {
        "uz": "uz-latn", "uz-latn-uz": "uz-latn", "uz-cyrl": "uz-cyr",
        "uz-cyrl-uz": "uz-cyr", "en-us": "en", "en-gb": "en",
        "ru-ru": "ru",
    }
    value = aliases.get(value, value)
    return value if value in VALID_LOCALES else "ru"


def locale_from_telegram(raw: Optional[str]) -> str:
    return normalize_locale(raw)


