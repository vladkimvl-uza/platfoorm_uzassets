_TAG_OR_VAR_RE = re.compile(r"(<[^>]+>|\{[^{}]+\}|https?://\S+)")
_WORD_RE = re.compile(r"[A-Za-zʻʼ'`’]+")
_DIGRAPHS = (
    ("Oʻ", "Ў"), ("O'", "Ў"), ("oʻ", "ў"), ("o'", "ў"),
    ("Gʻ", "Ғ"), ("G'", "Ғ"), ("gʻ", "ғ"), ("g'", "ғ"),
    ("Sh", "Ш"), ("sh", "ш"), ("Ch", "Ч"), ("ch", "ч"),
    ("Yo", "Ё"), ("yo", "ё"), ("Ya", "Я"), ("ya", "я"),
    ("Yu", "Ю"), ("yu", "ю"), ("Ye", "Е"), ("ye", "е"),
)
_SINGLES = str.maketrans({
    "a": "а", "b": "б", "c": "с", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "ҳ", "i": "и", "j": "ж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "қ", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "x": "х", "y": "й", "z": "з",
    "A": "А", "B": "Б", "C": "С", "D": "Д", "E": "Е", "F": "Ф", "G": "Г",
    "H": "Ҳ", "I": "И", "J": "Ж", "K": "К", "L": "Л", "M": "М", "N": "Н",
    "O": "О", "P": "П", "Q": "Қ", "R": "Р", "S": "С", "T": "Т", "U": "У",
    "V": "В", "X": "Х", "Y": "Й", "Z": "З",
    "ʻ": "ъ", "ʼ": "ъ", "'": "ъ", "`": "ъ", "’": "ъ",
})


def _to_cyr_word(word: str) -> str:
    if word in {"UzAssets", "Telegram"} or re.fullmatch(r"[A-Z0-9./+%-]{2,}", word):
        return word
    out = word
    for src, dst in _DIGRAPHS:
        out = out.replace(src, dst)
    return out.translate(_SINGLES).replace("'", "ъ").replace("ʻ", "ъ")


def _to_cyr(text: str) -> str:
    parts = _TAG_OR_VAR_RE.split(text)
    return "".join(
        part if _TAG_OR_VAR_RE.fullmatch(part or "")
        else _WORD_RE.sub(lambda m: _to_cyr_word(m.group(0)), part)
        for part in parts
    )


def msg(key: str, locale: Optional[str] = None, **values: Any) -> str:
    loc = normalize_locale(locale)
    if loc == "en":
        template = EN.get(key, RU.get(key, key))
    elif loc in ("uz-latn", "uz-cyr"):
        template = UZ.get(key, RU.get(key, key))
        if loc == "uz-cyr":
            template = _to_cyr(template)
    else:
        template = RU.get(key, key)
    if values:
        try:
            return template.format(**values)
        except (KeyError, ValueError, IndexError):
            return template
    return template
